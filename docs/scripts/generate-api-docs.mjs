#!/usr/bin/env node
/**
 * Generate API docs pages from the OpenAPI/AsyncAPI specs that the frontend uses.
 *
 * Why: keeps `docs/docs/api/*` in sync with the actual server contract without
 * hand-editing long endpoint lists.
 *
 * Usage (from repo root):
 *   node docs/scripts/generate-api-docs.mjs
 *
 * Optionally override inputs:
 *   OPENAPI_PATH=... ASYNCAPI_PATH=... node docs/scripts/generate-api-docs.mjs
 */

import { access, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..', '..');

const openapiPath =
  process.env.OPENAPI_PATH ??
  path.join(repoRoot, 'frontend', 'src', 'lib', 'ts-bindings', 'http', 'openapi.json');
const asyncapiPath =
  process.env.ASYNCAPI_PATH ??
  path.join(repoRoot, 'frontend', 'src', 'lib', 'ts-bindings', 'ws', 'asyncapi.json');

const apiDocsDir = path.join(repoRoot, 'docs', 'docs', 'api');
const apiDocOutputs = ['http.md', 'websockets.md', 'networktables.md'].map((file) =>
  path.join(apiDocsDir, file),
);

const HTTP_BASE_PREFIX = '/v1';

function mdEscape(text) {
  return String(text ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function stableMethodOrder(method) {
  // Roughly matches common documentation conventions.
  const order = { GET: 0, POST: 1, PUT: 2, PATCH: 3, DELETE: 4, OPTIONS: 5, HEAD: 6 };
  return order[method] ?? 99;
}

function firstMeaningfulResponseDescription(responses) {
  if (!responses || typeof responses !== 'object') return '';
  const codes = Object.keys(responses).sort((a, b) => {
    const ai = a === 'default' ? 999 : Number(a);
    const bi = b === 'default' ? 999 : Number(b);
    return ai - bi;
  });
  for (const code of codes) {
    const desc = responses?.[code]?.description;
    if (desc && String(desc).trim()) return String(desc).trim();
  }
  return '';
}

function collectOpenApiOperations(openapi) {
  const methods = ['get', 'post', 'put', 'patch', 'delete', 'options', 'head'];
  const ops = [];
  for (const [p, item] of Object.entries(openapi.paths ?? {})) {
    for (const m of methods) {
      const op = item?.[m];
      if (!op) continue;
      const method = m.toUpperCase();
      const tag = Array.isArray(op.tags) && op.tags.length ? op.tags[0] : 'Other';
      const summary =
        (op.summary && String(op.summary).trim()) ||
        (op.description && String(op.description).trim()) ||
        firstMeaningfulResponseDescription(op.responses) ||
        '';
      const responseCodes = Object.keys(op.responses ?? {}).sort((a, b) => {
        const ai = a === 'default' ? 999 : Number(a);
        const bi = b === 'default' ? 999 : Number(b);
        return ai - bi;
      });
      ops.push({
        tag,
        method,
        path: p,
        operationId: op.operationId ?? '',
        summary,
        responseCodes,
        deprecated: Boolean(op.deprecated),
      });
    }
  }
  return ops;
}

function renderHttpApiDoc(openapi, sourcePath) {
  const ops = collectOpenApiOperations(openapi);
  const tags = Array.isArray(openapi.tags) ? openapi.tags.map((t) => t?.name).filter(Boolean) : [];
  const tagOrder = new Map(tags.map((t, i) => [t, i]));

  const byTag = new Map();
  for (const op of ops) {
    const list = byTag.get(op.tag) ?? [];
    list.push(op);
    byTag.set(op.tag, list);
  }

  const sortedTags = Array.from(byTag.keys()).sort((a, b) => {
    const ai = tagOrder.has(a) ? tagOrder.get(a) : 999;
    const bi = tagOrder.has(b) ? tagOrder.get(b) : 999;
    if (ai !== bi) return ai - bi;
    return a.localeCompare(b);
  });

  const lines = [];
  lines.push('---');
  lines.push('title: HTTP API');
  lines.push('description: REST-ish HTTP endpoints exposed by helios-api.');
  lines.push('---');
  lines.push('');
  lines.push('<!--');
  lines.push('  This page is generated by `docs/scripts/generate-api-docs.mjs`.');
  lines.push(`  Source: ${path.relative(repoRoot, sourcePath)}`);
  lines.push('-->');
  lines.push('');
  lines.push('HeliOS exposes an HTTP API under the `/v1` prefix.');
  lines.push('');
  lines.push('- Base prefix: `/v1`');
  lines.push('- OpenAPI: `GET /openapi.json` (or `GET /v1/openapi.json`)');
  lines.push('');
  lines.push('## Endpoint Index');
  lines.push('');

  for (const tag of sortedTags) {
    const list = (byTag.get(tag) ?? []).slice().sort((a, b) => {
      if (a.path !== b.path) return a.path.localeCompare(b.path);
      const am = stableMethodOrder(a.method);
      const bm = stableMethodOrder(b.method);
      if (am !== bm) return am - bm;
      return String(a.operationId).localeCompare(String(b.operationId));
    });

    lines.push(`### ${tag}`);
    lines.push('');
    lines.push('| Method | Path | Description | Responses |');
    lines.push('|---|---|---|---|');
    for (const op of list) {
      const method = op.method;
      const fullPath = `${HTTP_BASE_PREFIX}${op.path}`;
      const descSuffix = op.deprecated ? ' **(deprecated)**' : '';
      const desc = (op.summary ? mdEscape(op.summary) : mdEscape(op.operationId)) + descSuffix;
      const responses = op.responseCodes.join(', ');
      lines.push(`| \`${method}\` | \`${fullPath}\` | ${desc} | \`${responses}\` |`);
    }
    lines.push('');
  }

  return lines.join('\n');
}

function renderWebSocketApiDoc(asyncapi, sourcePath) {
  const channels = asyncapi.channels ?? {};
  const channelKeys = Object.keys(channels).sort((a, b) => a.localeCompare(b));

  const lines = [];
  lines.push('---');
  lines.push('title: WebSocket API');
  lines.push('description: WebSocket channels and message schemas exposed by helios-api.');
  lines.push('---');
  lines.push('');
  lines.push('<!--');
  lines.push('  This page is generated by `docs/scripts/generate-api-docs.mjs`.');
  lines.push(`  Source: ${path.relative(repoRoot, sourcePath)}`);
  lines.push('-->');
  lines.push('');
  lines.push('HeliOS exposes a WebSocket endpoint at `/v1/ws`.');
  lines.push('');
  lines.push('- WebSocket URL: `ws(s)://<host>/v1/ws`');
  lines.push('- AsyncAPI: `GET /asyncapi.json` (or `GET /v1/asyncapi.json`)');
  lines.push('');
  lines.push('## Channels');
  lines.push('');
  lines.push('| Channel | Summary | Messages |');
  lines.push('|---|---|---|');

  for (const key of channelKeys) {
    const ch = channels[key] ?? {};
    const address = ch.address ?? key;
    const messages = ch.messages ?? {};
    const messageNames = Object.keys(messages).sort((a, b) => a.localeCompare(b));
    const firstMsg = messageNames.length ? messages[messageNames[0]] : null;
    const summary =
      (firstMsg?.summary && String(firstMsg.summary).trim()) ||
      (firstMsg?.description && String(firstMsg.description).trim()) ||
      '';
    const msgList = messageNames.map((m) => `\`${m}\``).join(', ');
    lines.push(`| \`${mdEscape(address)}\` | ${mdEscape(summary)} | ${msgList} |`);
  }

  lines.push('');
  lines.push('## Message Details');
  lines.push('');

  for (const key of channelKeys) {
    const ch = channels[key] ?? {};
    const address = ch.address ?? key;
    const messages = ch.messages ?? {};
    const messageNames = Object.keys(messages).sort((a, b) => a.localeCompare(b));
    // MDX treats `{foo}` as a JS expression; keep channel names (which may contain `{}`) in code.
    lines.push(`### \`${address}\``);
    lines.push('');
    for (const msgName of messageNames) {
      const msg = messages[msgName] ?? {};
      const summary = (msg.summary && String(msg.summary).trim()) || '';
      const desc = (msg.description && String(msg.description).trim()) || '';
      lines.push(`#### \`${msgName}\``);
      lines.push('');
      if (summary) lines.push(`- Summary: ${mdEscape(summary)}`);
      if (desc) lines.push(`- Description: ${mdEscape(desc)}`);
      lines.push('');
    }
  }

  return lines.join('\n');
}

function renderNt4Doc(openapi) {
  const ops = collectOpenApiOperations(openapi);

  const relevant = ops.filter((op) => op.tag === 'NT4' || op.path.startsWith('/device/nt4'));
  relevant.sort((a, b) => {
    if (a.path !== b.path) return a.path.localeCompare(b.path);
    const am = stableMethodOrder(a.method);
    const bm = stableMethodOrder(b.method);
    return am - bm;
  });

  const lines = [];
  lines.push('---');
  lines.push('title: NetworkTables');
  lines.push('description: NT4 helpers and integration points exposed by helios-api.');
  lines.push('---');
  lines.push('');
  lines.push('NetworkTables (NT4) is used for integrations with FRC-style tooling and peers.');
  lines.push('');
  lines.push('## HTTP Helpers');
  lines.push('');
  lines.push('These endpoints live under `/v1/*` (see also `GET /openapi.json`).');
  lines.push('');
  lines.push('| Method | Path | Description |');
  lines.push('|---|---|---|');
  for (const op of relevant) {
    const fullPath = `${HTTP_BASE_PREFIX}${op.path}`;
    const desc = op.summary ? mdEscape(op.summary) : mdEscape(op.operationId);
    lines.push(`| \`${op.method}\` | \`${fullPath}\` | ${desc} |`);
  }
  lines.push('');
  lines.push('## Default Ports');
  lines.push('');
  lines.push('- Common NT4 server port in this repo: `5810` (see backend probe logic).');
  lines.push('');
  lines.push('## Notes');
  lines.push('');
  lines.push('- NT4 subscriptions can be disabled via the device NT4 settings (`/v1/device/nt4`).');
  lines.push('- If you are integrating a third-party NT4 server (for example PhotonVision), configure host/port in settings and use the helpers above to inspect topics/values.');

  return lines.join('\n');
}

async function main() {
  const haveOpenApi = await pathExists(openapiPath);
  const haveAsyncApi = await pathExists(asyncapiPath);

  if (!haveOpenApi || !haveAsyncApi) {
    const outputsReady = await Promise.all(apiDocOutputs.map((file) => pathExists(file)));
    if (outputsReady.every(Boolean)) {
      const missing = [];
      if (!haveOpenApi) missing.push(path.relative(repoRoot, openapiPath));
      if (!haveAsyncApi) missing.push(path.relative(repoRoot, asyncapiPath));
      console.warn(
        `[generate-api-docs] Skipping regeneration because required spec inputs are missing: ${missing.join(', ')}. Using checked-in API docs pages instead.`,
      );
      return;
    }

    const missing = [];
    if (!haveOpenApi) missing.push(path.relative(repoRoot, openapiPath));
    if (!haveAsyncApi) missing.push(path.relative(repoRoot, asyncapiPath));
    throw new Error(
      `Missing API spec inputs: ${missing.join(', ')}. Provide OPENAPI_PATH/ASYNCAPI_PATH or restore the generated spec files.`,
    );
  }

  const openapi = JSON.parse(await readFile(openapiPath, 'utf8'));
  const asyncapi = JSON.parse(await readFile(asyncapiPath, 'utf8'));

  await writeFile(path.join(apiDocsDir, 'http.md'), renderHttpApiDoc(openapi, openapiPath), 'utf8');
  await writeFile(
    path.join(apiDocsDir, 'websockets.md'),
    renderWebSocketApiDoc(asyncapi, asyncapiPath),
    'utf8',
  );
  await writeFile(path.join(apiDocsDir, 'networktables.md'), renderNt4Doc(openapi), 'utf8');
}

async function pathExists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

main().catch((err) => {
  console.error('[generate-api-docs:error]', err?.stack || err?.message || String(err));
  process.exit(1);
});
