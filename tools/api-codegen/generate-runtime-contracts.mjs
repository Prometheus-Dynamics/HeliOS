#!/usr/bin/env node
import path from 'path';
import { fileURLToPath } from 'url';
import { mkdir, readFile, writeFile } from 'fs/promises';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..', '..');
const specPath = path.join(__dirname, 'runtime-contracts.json');
const rustOutputPath = path.join(repoRoot, 'backend', 'src', 'helios-engine', 'src', 'contracts', 'generated_runtime_contracts.rs');
const tsOutputPath = path.join(repoRoot, 'frontend', 'src', 'lib', 'ts-bindings', 'runtimeContracts.ts');

function upperSnake(value) {
  return String(value)
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toUpperCase();
}

function renderRust(spec) {
  const streamEntries = Object.entries(spec.streamIds)
    .map(([key, value]) => `    pub const ${upperSnake(key)}: Uuid = uuid::uuid!(${JSON.stringify(value)});`)
    .join('\n');

  const localizationEntries = Object.entries(spec.localization)
    .map(([key, value]) => `    pub const ${upperSnake(key)}: &str = ${JSON.stringify(value)};`)
    .join('\n');

  return `// Generated by tools/api-codegen/generate-runtime-contracts.mjs. Do not edit by hand.

pub mod stream_ids {
    use uuid::Uuid;

${streamEntries}
}

pub mod localization {
${localizationEntries}
}
`;
}

function renderTs(spec) {
  const streamEntries = Object.entries(spec.streamIds)
    .map(([key, value]) => `export const ${upperSnake(key)} = ${JSON.stringify(value)};`)
    .join('\n');

  const localizationEntries = Object.entries(spec.localization)
    .map(([key, value]) => `export const ${upperSnake(key)} = ${JSON.stringify(value)};`)
    .join('\n');

  const deviceImuExternalSourceId = String(spec.localization.deviceImuExternalSourceId ?? '').trim();
  const deviceImuExternalStreamId = `external:${deviceImuExternalSourceId}`;

  return `/* Generated by tools/api-codegen/generate-runtime-contracts.mjs. Do not edit by hand. */

${streamEntries}
${localizationEntries}

export const STREAM_PIPELINE_UUIDS = {
  RAW: RAW_PIPELINE_UUID,
  LEGACY_RAW: LEGACY_RAW_PIPELINE_UUID,
  CALIBRATION_MODE: CALIBRATION_MODE_PIPELINE_UUID
} as const;

export const LOCALIZATION_EXTERNAL_SOURCE_IDS = {
  DEVICE_IMU: DEVICE_IMU_EXTERNAL_SOURCE_ID
} as const;

export const LOCALIZATION_EXTERNAL_STREAM_IDS = {
  DEVICE_IMU: ${JSON.stringify(deviceImuExternalStreamId)}
} as const;
`;
}

export async function generateRuntimeContracts() {
  const spec = JSON.parse(await readFile(specPath, 'utf8'));
  await mkdir(path.dirname(rustOutputPath), { recursive: true });
  await mkdir(path.dirname(tsOutputPath), { recursive: true });
  await writeFile(rustOutputPath, renderRust(spec));
  await writeFile(tsOutputPath, renderTs(spec));
  return { rustOutputPath, tsOutputPath };
}

async function main() {
  const { rustOutputPath: rustPath, tsOutputPath: tsPath } = await generateRuntimeContracts();
  console.log(`[runtime-contract-codegen] Wrote ${path.relative(repoRoot, rustPath)}`);
  console.log(`[runtime-contract-codegen] Wrote ${path.relative(repoRoot, tsPath)}`);
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  main().catch((error) => {
    console.error('[runtime-contract-codegen:error]', error.message);
    process.exit(1);
  });
}
