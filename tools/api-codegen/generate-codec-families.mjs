#!/usr/bin/env node
import path from 'path';
import { fileURLToPath } from 'url';
import { mkdir, readFile, writeFile } from 'fs/promises';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..', '..');
const specPath = path.join(__dirname, 'codec-families.json');
const rustOutputPath = path.join(repoRoot, 'backend', 'src', 'helios-engine', 'src', 'ipc', 'types', 'generated_codec_families.rs');
const tsOutputPath = path.join(repoRoot, 'frontend', 'src', 'lib', 'ts-bindings', 'codecFamilies.ts');

function constantCase(value) {
  return String(value)
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toUpperCase();
}

function renderRustArray(values) {
  if (!values.length) return '&[]';
  return `&[${values.map((value) => JSON.stringify(value)).join(', ')}]`;
}

function renderRust(spec) {
  const selectorConsts = spec.encoderFamilies
    .map((family) => `pub(super) const ${constantCase(`encoder_selector_id_${family.id}`)}: &str = ${JSON.stringify(family.selectorId)};`)
    .join('\n');

  const entries = spec.encoderFamilies
    .map(
      (family) => `    GeneratedEncoderFamilySpec {
        variant: GeneratedEncoderFamilyVariant::${family.rustVariant},
        selector_id: ${constantCase(`encoder_selector_id_${family.id}`)},
        selector_aliases: ${renderRustArray(family.selectorAliases)},
        runtime_implementation_aliases: ${renderRustArray(family.runtimeImplementationAliases)},
        runtime_name_aliases: ${renderRustArray(family.runtimeNameAliases)},
        output_fourcc_aliases: ${renderRustArray(family.outputFourccAliases)},
        recording_codec: ${family.recordingCodec == null ? 'None' : `Some(${JSON.stringify(family.recordingCodec)})`},
    }`
    )
    .join(',\n');

  return `// Generated by tools/api-codegen/generate-codec-families.mjs. Do not edit by hand.

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub(super) enum GeneratedEncoderFamilyVariant {
${spec.encoderFamilies.map((family) => `    ${family.rustVariant},`).join('\n')}
}

#[derive(Debug, Clone, Copy)]
pub(super) struct GeneratedEncoderFamilySpec {
    pub variant: GeneratedEncoderFamilyVariant,
    pub selector_id: &'static str,
    pub selector_aliases: &'static [&'static str],
    pub runtime_implementation_aliases: &'static [&'static str],
    pub runtime_name_aliases: &'static [&'static str],
    pub output_fourcc_aliases: &'static [&'static str],
    pub recording_codec: Option<&'static str>,
}

${selectorConsts}

pub(super) const GENERATED_ENCODER_FAMILY_SPECS: &[GeneratedEncoderFamilySpec] = &[
${entries}
];
`;
}

function renderTs(spec) {
  const idEntries = spec.encoderFamilies
    .map((family) => `  ${constantCase(family.id)}: ${JSON.stringify(family.id)}`)
    .join(',\n');

  const selectorEntries = spec.encoderFamilies
    .map((family) => `  ${constantCase(family.id)}: ${JSON.stringify(family.selectorId)}`)
    .join(',\n');

  return `/* Generated by tools/api-codegen/generate-codec-families.mjs. Do not edit by hand. */

export const STREAM_ENCODER_FAMILY_IDS = {
${idEntries}
} as const;

export const STREAM_ENCODER_SELECTOR_IDS = {
${selectorEntries}
} as const;

export const STREAM_ENCODER_FAMILIES = ${JSON.stringify(spec.encoderFamilies, null, 2)} as const;

export type StreamEncoderFamily = (typeof STREAM_ENCODER_FAMILIES)[number];
export type StreamEncoderFamilyId = StreamEncoderFamily['id'];
export type StreamEncoderSelectionId = StreamEncoderFamily['selectorId'];
export type StreamRecordingCodecId = Exclude<StreamEncoderFamily['recordingCodec'], null>;
`;
}

export async function generateCodecFamilies() {
  const spec = JSON.parse(await readFile(specPath, 'utf8'));
  await mkdir(path.dirname(rustOutputPath), { recursive: true });
  await mkdir(path.dirname(tsOutputPath), { recursive: true });
  await writeFile(rustOutputPath, renderRust(spec));
  await writeFile(tsOutputPath, renderTs(spec));
  return { rustOutputPath, tsOutputPath };
}

async function main() {
  const { rustOutputPath: rustPath, tsOutputPath: tsPath } = await generateCodecFamilies();
  console.log(`[codec-family-codegen] Wrote ${path.relative(repoRoot, rustPath)}`);
  console.log(`[codec-family-codegen] Wrote ${path.relative(repoRoot, tsPath)}`);
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  main().catch((error) => {
    console.error('[codec-family-codegen:error]', error.message);
    process.exit(1);
  });
}
